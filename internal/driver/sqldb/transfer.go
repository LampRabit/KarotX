// session returns a dedicated connection that is discarded (not pooled) on
// release, so session state set during export/import can't leak.
func (c *conn) session(ctx context.Context, schema string) (*sql.Conn, func(), error) {
	sc, err := c.db.Conn(ctx)
	if err != nil {
		return nil, nil, err
	}
	release := func() {
		sc.Raw(func(any) error { return sqldriver.ErrBadConn })
		sc.Close()
	}
	if use := c.d.useSchema(schema); schema != "" && use != "" {
		if _, err := sc.ExecContext(ctx, use); err != nil {
			release()
			return nil, nil, err
		}
	}
	return sc, release, nil
}

func (c *conn) StreamRows(ctx context.Context, query, schema string, head func([]driver.Column) error, row func([]any) error) error {
	sc, release, err := c.session(ctx, schema)
	if err != nil {
		return err
	}
	defer release()
	// Exports only read: SQLite has no read-only transactions, so it uses query_only.
	var q interface {
		QueryContext(context.Context, string, ...any) (*sql.Rows, error)
	} = sc
	if c.d.name() == "sqlite" {
		if _, err := sc.ExecContext(ctx, "PRAGMA query_only = 1"); err != nil {
			return err
		}
	} else {
		tx, err := sc.BeginTx(ctx, &sql.TxOptions{ReadOnly: true})
		if err != nil {
			return err
		}
		defer tx.Rollback()
		q = tx
	}
	rows, err := q.QueryContext(ctx, query)
	if err != nil {
		return err
	}
	defer rows.Close()
	types, err := rows.ColumnTypes()
	if err != nil {
		return err
	}
	cols := make([]driver.Column, len(types))
	for i, t := range types {
		cols[i] = driver.Column{Name: t.Name(), Type: strings.ToLower(t.DatabaseTypeName())}
	}
	if err := head(cols); err != nil {
		return err
	}
	vals, ptrs := make([]any, len(cols)), make([]any, len(cols))
	for rows.Next() {
		for i := range vals {
			vals[i], ptrs[i] = nil, &vals[i]
		}
		if err := rows.Scan(ptrs...); err != nil {
			return err
		}
		for i, v := range vals {
			if b, ok := v.([]byte); ok && !utf8.Valid(b) {
				vals[i] = append([]byte(nil), b...)
			} else {
				vals[i] = jsonValue(v)
			}
		}
		if err := row(vals); err != nil {
			return err
		}
	}
	return rows.Err()
}

func (c *conn) CreateTableSQL(ctx context.Context, t driver.TableRef) (string, error) {
	var ddl string
	switch c.d.name() {
	case "sqlite":
		err := c.db.QueryRowContext(ctx, `SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?`, t.Table).Scan(&ddl)
		return ddl, err
	case "mysql":
		var name string
		err := c.db.QueryRowContext(ctx, "SHOW CREATE TABLE "+c.qualify(t)).Scan(&name, &ddl)
		return ddl, err
	}
	// Postgres has no SHOW CREATE TABLE: build it from the catalog.
	cols, err := c.Columns(ctx, t)
	if err != nil {
		return "", err
	}
	if len(cols) == 0 {
		return "", fmt.Errorf("table %s not found", t.Table)
	}
	var defs, pk []string
	for _, col := range cols {
		def := c.d.quote(col.Name) + " " + col.Type
		if col.AutoIncrement {
			def += " GENERATED BY DEFAULT AS IDENTITY"
		} else if col.Default != nil {
			def += " DEFAULT " + *col.Default
		}
		if !col.Nullable {
			def += " NOT NULL"
		}
		defs = append(defs, def)
		if col.PrimaryKey {
			pk = append(pk, c.d.quote(col.Name))
		}
	}
	if len(pk) > 0 {
		defs = append(defs, "PRIMARY KEY ("+strings.Join(pk, ", ")+")")
	}
	return "CREATE TABLE " + c.d.quote(t.Table) + " (\n  " + strings.Join(defs, ",\n  ") + "\n)", nil
}

func (c *conn) InsertRows(ctx context.Context, t driver.TableRef, cols []string, rows [][]any, clear bool) (int64, error) {
	if len(cols) == 0 {
		return 0, errors.New("choose at least one column")
	}
	table := c.qualify(t)
	quoted := make([]string, len(cols))
	for i, col := range cols {
		quoted[i] = c.d.quote(col)
	}
	head := fmt.Sprintf("INSERT INTO %s (%s) VALUES ", table, strings.Join(quoted, ", "))
	// Stay well under every driver's bound-parameter limit (SQLite: 32766, Postgres/MySQL: 65535).
	per := max(1, min(500, 30000/len(cols)))

	tx, err := c.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	if clear {
		if _, err := tx.ExecContext(ctx, "DELETE FROM "+table); err != nil {
			return 0, err
		}
	}
	for start := 0; start < len(rows); start += per {
		chunk := rows[start:min(start+per, len(rows))]
		var b strings.Builder
		b.WriteString(head)
		args := make([]any, 0, len(chunk)*len(cols))
		for i, r := range chunk {
			if len(r) != len(cols) {
				return 0, fmt.Errorf("row %d has %d values, expected %d", start+i+1, len(r), len(cols))
			}
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteByte('(')
			for j, v := range r {
				if j > 0 {
					b.WriteString(", ")
				}
				args = append(args, plainValue(v))
				b.WriteString(c.d.placeholder(len(args)))
			}
			b.WriteByte(')')
		}
		if _, err := tx.ExecContext(ctx, b.String(), args...); err != nil {
			return 0, fmt.Errorf("rows %d–%d: %w", start+1, start+len(chunk), err)
		}
	}
	return int64(len(rows)), tx.Commit()
}

// plainValue turns nested JSON (objects, arrays) into JSON text for the column.
func plainValue(v any) any {
	switch v.(type) {
	case map[string]any, []any:
		b, _ := json.Marshal(v)
		return string(b)
	}
	return v
}

func (c *conn) ExecScript(ctx context.Context, script, schema string, continueOnError bool, progress func(done, total int, err error, stmt string)) error {
	stmts := driver.SplitSQL(script, c.d.hashComments())
	if len(stmts) == 0 {
		return errors.New("the file has no SQL statements")
	}
	sc, release, err := c.session(ctx, schema)
	if err != nil {
		return err
	}
	defer release()
	var first error
	for i, s := range stmts {
		_, err := sc.ExecContext(ctx, s)
		if ctx.Err() != nil {
			return ctx.Err()
		}
		progress(i+1, len(stmts), err, s)
		if err != nil {
			if !continueOnError {
				return err
			}
			if first == nil {
				first = err
			}
		}
	}
	return first
}

func (c *conn) Quote(id string) string { return c.d.quote(id) }

func (c *conn) Literal(v any) string {
	switch x := v.(type) {
	case []byte:
		if c.d.name() == "postgres" {
			return `'\x` + hex.EncodeToString(x) + `'::bytea`
		}
		return "X'" + hex.EncodeToString(x) + "'"
	case string:
		if c.d.name() == "mysql" { // backslash is an escape character in MySQL strings
			return "'" + strings.NewReplacer(`\`, `\\`, "'", "''").Replace(x) + "'"
		}
	}
	return literal(v)
}
