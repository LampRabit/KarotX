import type { ColumnInfo, DriverName } from './api'

/** Generates DDL for the table designer and database actions, per dialect. */

export const q = (d: DriverName, id: string) =>
  d === 'mysql' ? '`' + id.replace(/`/g, '``') + '`' : '"' + id.replace(/"/g, '""') + '"'

const qualify = (d: DriverName, schema: string, table: string) =>
  d === 'sqlite' ? q(d, table) : `${q(d, schema)}.${q(d, table)}`

export const typeSuggestions: Record<DriverName, string[]> = {
  postgres: ['bigint', 'integer', 'text', 'varchar(255)', 'boolean', 'numeric(10,2)', 'double precision', 'date', 'timestamp', 'timestamptz', 'uuid', 'jsonb', 'bytea'],
  mysql: ['bigint', 'int', 'varchar(255)', 'text', 'tinyint(1)', 'decimal(10,2)', 'double', 'date', 'datetime', 'timestamp', 'json', 'blob'],
  sqlite: ['INTEGER', 'TEXT', 'REAL', 'NUMERIC', 'BLOB'],
}

/** A column in the designer. `orig` is the name it had in the database (undefined = new). */
export type DesignColumn = {
  key: string
  orig?: string
  name: string
  type: string
  nullable: boolean
  default: string // raw SQL expression, '' = none
  primaryKey: boolean
  autoIncrement: boolean
}

export const fromInfo = (c: ColumnInfo, i: number): DesignColumn => ({
  key: `c${i}`,
  orig: c.name,
  name: c.name,
  type: c.type,
  nullable: c.nullable,
  default: c.autoIncrement ? '' : (c.default ?? ''),
  primaryKey: c.primaryKey,
  autoIncrement: c.autoIncrement,
})

function columnDef(d: DriverName, c: DesignColumn, inlinePk: boolean) {
  const parts = [q(d, c.name)]
  if (c.autoIncrement && d === 'postgres') parts.push(c.type || 'bigint', 'GENERATED BY DEFAULT AS IDENTITY')
  else parts.push(c.type || (d === 'sqlite' ? 'TEXT' : 'text'))
  if (inlinePk) parts.push('PRIMARY KEY' + (c.autoIncrement ? ' AUTOINCREMENT' : ''))
  if (!c.nullable && !inlinePk) parts.push('NOT NULL')
  if (c.autoIncrement && d === 'mysql') parts.push('AUTO_INCREMENT')
  if (c.default.trim() && !c.autoIncrement) parts.push('DEFAULT ' + c.default.trim())
  return parts.join(' ')
}

export function createTable(d: DriverName, schema: string, name: string, cols: DesignColumn[]) {
  const pk = cols.filter((c) => c.primaryKey)
  // SQLite AUTOINCREMENT only works as an inline single-column INTEGER PRIMARY KEY.
  const inline = d === 'sqlite' && pk.length === 1 && pk[0].autoIncrement
  const lines = cols.map((c) => '  ' + columnDef(d, c, inline && c.primaryKey))
  if (pk.length && !inline) lines.push(`  PRIMARY KEY (${pk.map((c) => q(d, c.name)).join(', ')})`)
  return [`CREATE TABLE ${qualify(d, schema, name)} (\n${lines.join(',\n')}\n)`]
}

/** ALTER statements turning `before` into `after`. Returns warnings for changes a dialect can't do. */
export function alterTable(d: DriverName, schema: string, table: string, newName: string, before: ColumnInfo[], after: DesignColumn[]) {
  const stmts: string[] = []
  const warnings: string[] = []
  const t = qualify(d, schema, table)
  const kept = new Set(after.filter((c) => c.orig).map((c) => c.orig))

  for (const b of before) if (!kept.has(b.name)) stmts.push(`ALTER TABLE ${t} DROP COLUMN ${q(d, b.name)}`)

  for (const c of after) {
    if (!c.orig) {
      stmts.push(`ALTER TABLE ${t} ADD COLUMN ${columnDef(d, { ...c, primaryKey: false }, false)}`)
      if (c.primaryKey) warnings.push(`"${c.name}" was added without a primary key; change primary keys with SQL.`)
      continue
    }
    const b = before.find((x) => x.name === c.orig)!
    if (c.name !== c.orig) stmts.push(`ALTER TABLE ${t} RENAME COLUMN ${q(d, c.orig)} TO ${q(d, c.name)}`)
    const col = q(d, c.name)
    const typeChanged = c.type.trim().toLowerCase() !== b.type.toLowerCase()
    const nullChanged = c.nullable !== b.nullable
    const defChanged = !c.autoIncrement && c.default.trim() !== (b.default ?? '')
    if (!typeChanged && !nullChanged && !defChanged) continue
    if (d === 'sqlite') {
      warnings.push(`SQLite can't change the type, NULL or default of "${c.name}". Recreate the table to do that.`)
    } else if (d === 'mysql') {
      stmts.push(`ALTER TABLE ${t} MODIFY COLUMN ${columnDef(d, { ...c, primaryKey: false }, false)}`)
    } else {
      if (typeChanged) stmts.push(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${c.type} USING ${col}::${c.type}`)
      if (nullChanged) stmts.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`)
      if (defChanged) stmts.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${c.default.trim() ? 'SET DEFAULT ' + c.default.trim() : 'DROP DEFAULT'}`)
    }
  }

  if (newName && newName !== table) {
    stmts.push(d === 'mysql' ? `RENAME TABLE ${t} TO ${qualify(d, schema, newName)}` : `ALTER TABLE ${t} RENAME TO ${q(d, newName)}`)
  }
  return { stmts, warnings }
}

export const dropTable = (d: DriverName, schema: string, table: string, view = false) =>
  `DROP ${view ? 'VIEW' : 'TABLE'} ${qualify(d, schema, table)}`

export const emptyTable = (d: DriverName, schema: string, table: string) =>
  d === 'sqlite' ? `DELETE FROM ${qualify(d, schema, table)}` : `TRUNCATE TABLE ${qualify(d, schema, table)}`

export const createDatabase = (d: DriverName, name: string) =>
  d === 'mysql' ? `CREATE DATABASE ${q(d, name)} CHARACTER SET utf8mb4` : `CREATE SCHEMA ${q(d, name)}`

export const dropDatabase = (d: DriverName, name: string) =>
  d === 'mysql' ? `DROP DATABASE ${q(d, name)}` : `DROP SCHEMA ${q(d, name)} CASCADE`

/** What a "database" is called in the UI for each dialect. */
export const containerName = (d: DriverName) => (d === 'postgres' ? 'schema' : 'database')

export const selectSql = (d: DriverName, schema: string, table: string) =>
  `SELECT * FROM ${qualify(d, schema, table)}\nLIMIT 100;`
